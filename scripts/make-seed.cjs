// One-time: turns the original catalog.json into migrations/0002_seed.sql.
// After launch, the admin page is the way to change apps.
const fs = require('fs');
const path = require('path');
const src = JSON.parse(fs.readFileSync(process.argv[2] || path.join(__dirname, '../../catalog.json'), 'utf8'));

const drop = new Set(['HEVC Video Extensions', 'Gridfinity Generator', 'RaceStudio 3', 'LG Switch / Dual Controller', 'Thunderstore Mod Manager']);
const extra = [
  { name: 'r2modman', cat: 'Gaming', id: 'ebkr.r2modman', note: 'Thunderstore mod manager without Overwolf' },
  { name: 'Gale', cat: 'Gaming', id: 'Kesomannen.Gale', note: 'Fast Thunderstore mod manager' },
];
const homepages = {
  'StrokesPlus.net': 'https://www.strokesplus.net/',
  'DaVinci Resolve': 'https://www.blackmagicdesign.com/products/davinciresolve',
  'FUJIFILM X RAW STUDIO': 'https://fujifilm-x.com/global/support/download/software/x-raw-studio/',
  'SOLIDWORKS 2024': 'https://www.solidworks.com/',
  'vorpX': 'https://www.vorpx.com/',
  'Pulsar Fusion': 'https://www.pulsar.gg/pages/download',
  'GIGABYTE Control Center': 'https://www.gigabyte.com/Support/Utility',
  'ASUS Armoury Crate': 'https://rog.asus.com/armoury-crate/',
  'MSI Center': 'https://www.msi.com/Landing/MSI-Center',
  'NVIDIA App': 'https://www.nvidia.com/en-us/software/nvidia-app/',
  'Wootility': 'https://wooting.io/wootility',
};
const direct = {
  'Wootility': { url: 'https://api.wooting.io/public/wootility/download?os=win', args: '/S', detect: '^Wootility' },
  'NVIDIA App': {
    url: 'https://www.nvidia.com/en-us/software/nvidia-app/',
    url_pattern: 'https://us\\.download\\.nvidia\\.com/nvapp/client/[0-9.]+/x64/NVIDIA_app_v[0-9.]+_x64\\.exe',
    args: '-s -noreboot', detect: '^NVIDIA App',
  },
};
const requires = {
  'NVIDIA App': 'gpu:nvidia', 'NVIDIA Control Panel': 'gpu:nvidia', 'NVIDIA PhysX': 'gpu:nvidia',
  'AMD Software: Adrenalin': 'gpu:amd', 'Intel XTU': 'cpu:intel',
};
const renames = { 'SOLIDWORKS 2024': 'SOLIDWORKS', 'Intel Chipset / ME drivers': 'Intel Chipset Device Software', 'Intel Graphics / Driver & Support Assistant': 'Intel Driver & Support Assistant' };
const noteOverride = { "AMD Software: Adrenalin": "Only on AMD GPUs; installs the driver" };
const cleanNote = n => (n || '')
  .replace(/You have[^.;]*[.;]?\s*/i, '')
  .replace(/Installed per-user; not in winget list here/i, '')
  .replace(/\.?\s*Not on winget/i, '')
  .replace(/Microsoft Store;?\s*/i, '')
  .replace(/Not on winget;?\s*/i, '')
  .replace(/manual download from [^;.]*/i, 'Download from the vendor')
  .replace(/^[;.\s]+|[;.\s]+$/g, '')
  .replace(/^./, c => c.toUpperCase());

const slug = s => s.toLowerCase().replace(/\(.*?\)/g, '').replace(/[®™]/g, '').replace(/\+\+/g, 'pp').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
const rows = [];
const used = new Set();
const all = src.filter(a => !drop.has(a.name)).map(a => ({ name: a.name, cat: a.cat, id: a.id, choco: a.choco, note: a.note }));
for (const e of extra) {
  const i = all.findIndex(a => a.cat === e.cat);
  all.splice(i + 1, 0, e);
}
const sortInCat = {};
for (const a of all) {
  const name = renames[a.name] || a.name;
  let key = slug(name); while (used.has(key)) key += '-2'; used.add(key);
  let source, pkg = '';
  const d = direct[a.name];
  if (d) source = 'direct';
  else if (a.id && /^[0-9A-Z]{12}$/.test(a.id)) { source = 'msstore'; pkg = a.id; }
  else if (a.id) { source = 'winget'; pkg = a.id; }
  else if (a.choco) { source = 'choco'; pkg = a.choco; }
  else source = 'manual';
  sortInCat[a.cat] = (sortInCat[a.cat] || 0) + 10;
  rows.push({
    key, name, category: a.cat, source, pkg,
    url: d?.url || '', url_pattern: d?.url_pattern || '', args: d?.args || '', detect: d?.detect || '',
    requires: requires[a.name] || '', note: noteOverride[a.name] ?? cleanNote(a.note), homepage: homepages[a.name] || '',
    sort: sortInCat[a.cat],
  });
}
const q = v => typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const cols = ['key', 'name', 'category', 'source', 'pkg', 'url', 'url_pattern', 'args', 'detect', 'requires', 'note', 'homepage', 'sort'];
const sql = '-- Generated by scripts/make-seed.js\n' + rows.map(r => `INSERT INTO apps (${cols.join(', ')}) VALUES (${cols.map(c => q(r[c])).join(', ')});`).join('\n') + '\n';
fs.writeFileSync(path.join(__dirname, '../migrations/0002_seed.sql'), sql);
const by = rows.reduce((m, r) => (m[r.source] = (m[r.source] || 0) + 1, m), {});
console.log(rows.length, 'apps', JSON.stringify(by));
